    return {
        "name": _op("OPERATOR_NAME", "ИП Романенко Игорь Алексеевич"),
        "inn": _op("OPERATOR_INN"),
        "ogrnip": _op("OPERATOR_OGRNIP"),
        "address": _op("OPERATOR_ADDRESS"),
        "email": _op("OPERATOR_EMAIL"),
    }


