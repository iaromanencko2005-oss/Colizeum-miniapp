"""
Таблица призов рулетки.

Принцип честной рулетки: сумма вероятностей всегда 100%, и в колесе
специально есть исход "без приза" — иначе ожидаемая ценность одного
прокрута всегда положительна для клиента и отрицательна для клуба,
и через месяц-два акция станет по факту постоянной раздачей бонусов.
Ниже — рациональная раскладка: мелкие призы часто, крупные — редко,
джекпот — очень редко. Меняй `weight` под свою экономику: чем больше
цифра, тем чаще выпадает приз.

`value` — необязательное поле для призов-бонусов: сколько бонусных
баллов начислить. Для не-денежных призов (час игры, напиток, джекпот)
значение не задаётся — их начисляет администратор вручную по факту
показанного экрана.
"""
import random
from dataclasses import dataclass


@dataclass
class Prize:
    id: str
    label: str
    weight: float
    value: int | None = None  # бонусных баллов, если применимо


PRIZE_TABLE: list[Prize] = [
    Prize("empty", "Пусто — повезёт в следующий раз", 35, None),
    Prize("bonus_100", "+100 бонусов", 25, 100),
    Prize("bonus_300", "+300 бонусов", 15, 300),
    Prize("free_hour", "Бесплатный час игры", 10, None),
    Prize("bonus_500", "+500 бонусов", 8, 500),
    Prize("free_drink", "Бесплатный напиток", 5, None),
    Prize("bonus_1000", "+1000 бонусов", 1.5, 1000),
    Prize("jackpot", "Джекпот: сутки в приватной зоне бесплатно", 0.5, None),
]

assert abs(sum(p.weight for p in PRIZE_TABLE) - 100) < 1e-6, "Веса призов должны давать в сумме 100"


def spin() -> Prize:
    """Выбирает приз согласно весам — обычный взвешенный случайный выбор,
    без скрытых манипуляций и без завязки на то, сколько клиент когда-либо
    выиграл раньше."""
    weights = [p.weight for p in PRIZE_TABLE]
    return random.choices(PRIZE_TABLE, weights=weights, k=1)[0]
