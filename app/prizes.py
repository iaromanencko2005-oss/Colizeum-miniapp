"""
Таблица призов рулетки.

По решению владельца клуба рулетка не имеет пустого исхода — каждый
прокрут начисляет бонусные рубли. Бесплатные игры дают от 1 до 10
колизов: основной источник колизов — кэшбэк за пополнение в клубе.
Вероятности убывают от мелких сумм к крупным, в среднем ~4 колиза за прокрут.

Меняй `weight` под свою экономику: чем больше цифра, тем чаще выпадает
приз. Сумма весов должна оставаться равной 100.
"""
import random
from dataclasses import dataclass


@dataclass
class Prize:
    id: str
    label: str
    weight: float
    value: int  # бонусных рублей, начисляются на баланс


PRIZE_TABLE: list[Prize] = [   # бесплатный прокрут: от 1 до 10 колизов, в среднем ~4
    Prize("bonus_1", "+1 колиз", 16, 1),
    Prize("bonus_2", "+2 колиза", 15, 2),
    Prize("bonus_3", "+3 колиза", 14, 3),
    Prize("bonus_4", "+4 колиза", 13, 4),
    Prize("bonus_5", "+5 колизов", 12, 5),
    Prize("bonus_6", "+6 колизов", 10, 6),
    Prize("bonus_7", "+7 колизов", 8, 7),
    Prize("bonus_8", "+8 колизов", 6, 8),
    Prize("bonus_9", "+9 колизов", 4, 9),
    Prize("bonus_10", "+10 колизов", 2, 10),
]

assert abs(sum(p.weight for p in PRIZE_TABLE) - 100) < 1e-6, "Веса призов должны давать в сумме 100"


def spin() -> Prize:
    """Выбирает приз согласно весам — обычный взвешенный случайный выбор,
    без скрытых манипуляций и без завязки на то, сколько клиент когда-либо
    выиграл раньше. Считается на сервере — клиент никогда не выбирает приз сам."""
    weights = [p.weight for p in PRIZE_TABLE]
    return random.choices(PRIZE_TABLE, weights=weights, k=1)[0]
