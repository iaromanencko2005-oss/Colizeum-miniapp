"""
Таблица призов рулетки.

По решению владельца клуба рулетка не имеет пустого исхода — каждый
прокрут начисляет бонусные рубли. Себестоимость одной игры ~220 ₽,
поэтому суммы призов подобраны заметно ниже неё, а вероятности
убывают от мелких сумм к крупным. Средняя цена одного прокрута —
около 29 ₽ бонусами (проверено ниже автотестом весов).

Меняй `weight` под свою экономику: чем больше цифра, тем чаще выпадает
приз. Сумма весов должна оставаться равной 100.
"""
import random
from dataclasses import dataclass


@dataclass
class Prize:
    id: str
    label: str
    weight: float
    value: int  # бонусных рублей, начисляются на баланс


PRIZE_TABLE: list[Prize] = [
    Prize("bonus_10", "+10 бонусов", 30, 10),
    Prize("bonus_20", "+20 бонусов", 22, 20),
    Prize("bonus_30", "+30 бонусов", 16, 30),
    Prize("bonus_40", "+40 бонусов", 12, 40),
    Prize("bonus_50", "+50 бонусов", 9, 50),
    Prize("bonus_60", "+60 бонусов", 6, 60),
    Prize("bonus_70", "+70 бонусов", 3.5, 70),
    Prize("bonus_80", "+80 бонусов", 1.5, 80),
]

assert abs(sum(p.weight for p in PRIZE_TABLE) - 100) < 1e-6, "Веса призов должны давать в сумме 100"


def spin() -> Prize:
    """Выбирает приз согласно весам — обычный взвешенный случайный выбор,
    без скрытых манипуляций и без завязки на то, сколько клиент когда-либо
    выиграл раньше. Считается на сервере — клиент никогда не выбирает приз сам."""
    weights = [p.weight for p in PRIZE_TABLE]
    return random.choices(PRIZE_TABLE, weights=weights, k=1)[0]
