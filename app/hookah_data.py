_ROLE_ORDER = {"top": 0, "accent": 1, "base": 2}
_WEIGHT = {1: 6, 2: 5, 3: 4, 4: 3, 5: 2}


def _shares(fl: list[dict]) -> list[int]:
    """Пропорции в чаше, % (кратно 5): чем сильнее вкус, тем меньше его доля."""
    w = [_WEIGHT[f["intensity"]] for f in fl]
    raw = [x * 100 / sum(w) for x in w]
    out = [int(round(r / 5) * 5) for r in raw]
    out[out.index(max(out))] += 100 - sum(out)
    return out


def _sentence(s: str) -> str:
    s = s.strip()
    return (s[0].upper() + s[1:] + ("" if s.endswith((".", "!", "?")) else ".")) if s else ""


def mix_name(ids: list[str]) -> str:
    fl = [BY_ID[i] for i in ids]
    if len(fl) == 1:
        return fl[0]["name"]
    if len(fl) == 2:
        p = PAIRS.get(frozenset(ids))
        return p["name"] if p else f"{fl[0]['name']} и {fl[1]['name'].lower()}"
    order = sorted(fl, key=lambda f: (f["role"] == "accent", -_WEIGHT[f["intensity"]]))
    a, b, c = order[0], order[1], order[2]
    p = PAIRS.get(frozenset((a["id"], b["id"])))
    base = p["name"] if p else f"{a['name']} и {b['name'].lower()}"
    return f"{base} {c['ins']}"


def describe(ids: list[str]) -> dict:
    """Описание микса из 1–3 табаков."""
    ids = list(dict.fromkeys(ids))
    fl = [BY_ID[i] for i in ids]
    shares = _shares(fl)
    share = {f["id"]: s for f, s in zip(fl, shares)}
    by_lead = sorted(fl, key=lambda f: (_ROLE_ORDER[f["role"]], -f["intensity"]))
    first = by_lead[0]
    rest = [f for f in by_lead[1:]]
    accent = next((f for f in rest if f["role"] == "accent"), None)

    stages = [{"title": "Первые затяжки", "text": _sentence(first["first"])}]
    if not rest:
        stages.append({"title": "Середина чаши", "text": "Вкус становится ровнее и глубже — без резких переходов."})
        stages.append({"title": "Финиш", "text": _sentence(first["finish"])})
    else:
        middle = [f for f in rest if f is not accent] or rest
        b = middle[0]
        p = PAIRS.get(frozenset((first["id"], b["id"])))
        mid = f"Затем подключается {b['mid']}" + (f": {p['blend']}" if p else "")
        text = _sentence(mid)
        if len(middle) > 1:
            text += " " + _sentence(f"{middle[1]['mid']} {middle[1]['twist']}")
        stages.append({"title": "Середина чаши", "text": text})
        fin = accent or next((f for f in fl if f["role"] == "base"), None) or rest[-1]
        stages.append({"title": "Финиш", "text": _sentence(fin["finish"])})

    meters = {}
    for k, idx in (("sweet", 0), ("sour", 1), ("fresh", 2), ("dense", 3)):
        v = sum(f["meters"][idx] * share[f["id"]] for f in fl) / 100
        if any(f["meters"][idx] >= 4 for f in fl):
            v = max(v, 3)   # яркий вкус слышен даже малой долей
        meters[k] = max(1, min(5, int(v + 0.6)))

    lo = max(f["strength"][0] for f in fl)
    hi = min(f["strength"][1] for f in fl)
    if lo > hi:
        lo, hi = max(1, hi - 2), hi
    why = ""
    if any(f["role"] == "base" for f in fl):
        why = "на крепком десертные и сливочные ноты теряются"
    elif any(f["id"] == "mint" for f in fl):
        why = "холодок выдержит и покрепче"

    like = []
    if len(fl) > 1:
        pairs = [(x, y) for i, x in enumerate(fl) for y in fl[i + 1:]]
        pairs.sort(key=lambda xy: -(share[xy[0]["id"]] + share[xy[1]["id"]]))
        for x, y in pairs:
            p = PAIRS.get(frozenset((x["id"], y["id"])))
            if p:
                for item in p["like"]:
                    if item not in like:
                        like.append(item)
                        break
        if len(fl) == 2:
            p = PAIRS.get(frozenset(ids))
            if p and len(p["like"]) > 1:
                like = p["like"][:2]
        like = like[:2]

    tip = None
    if len(fl) < 3:
        best, score = None, 0
        for cand in GOOD["mint"] + [f["id"] for f in FLAVORS]:
            if cand in ids:
                continue
            sc = sum((cand in GOOD.get(i, [])) + (i in GOOD.get(cand, [])) for i in ids)
            if sc > score:
                best, score = cand, sc
        if best and len(fl) == 1:
            two = [g for g in GOOD.get(ids[0], []) if g in BY_ID][:2]
            tip = {"id": best, "text": "Хорошо сочетается " + " и ".join(BY_ID[g]["ins"] for g in two) + "."}
        elif best:
            tip = {"id": best, "text": f"Можно добавить «{BY_ID[best]['name']}» — {BY_ID[best]['twist']}."}

    return {
        "ids": ids,
        "name": mix_name(ids),
        "shares": [{"id": f["id"], "name": f["name"], "share": share[f["id"]], "c1": f["c1"], "c2": f["c2"]} for f in fl],
        "meters": meters,
        "stages": stages,
        "like": like,
        "strength": {"from": lo, "to": hi, "why": why},
        "tip": tip,
    }
